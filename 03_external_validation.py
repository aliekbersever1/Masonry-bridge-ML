def formula_f1_linear(K, L, W, H, E, rho):
    return 27.147 - 0.619*K - 0.302*L + 3.158*W - 1.019*H + 0.002*E - 0.4*rho


def formula_f1_symbolic(K, L, W, H, E, rho):
    with np.errstate(divide="ignore", invalid="ignore", over="ignore"):
        base = (W**1.5087 * E) / (H * rho)
        exponent = (K * L) ** (-0.1149)
        return base ** exponent


def formula_f2_linear(K, L, W, H, E, rho):
    return 46.402 - 1.221*K - 0.468*L + 3.307*W - 0.909*H + 0.003*E - 0.662*rho


def formula_f2_symbolic(K, L, W, H, E, rho):
    with np.errstate(divide="ignore", invalid="ignore", over="ignore"):
        return 15.549 * np.sqrt((W * E) / (K * L * rho))


