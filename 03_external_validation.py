def plot_observed_vs_predicted(df, true_col, methods_dict, title, filename):
    fig, ax = plt.subplots(figsize=(7, 6))

    for label, pred_col in methods_dict.items():
        valid = df[[true_col, pred_col]].dropna()
        if len(valid) > 0:
            mae, rmse, r2, mape = calculate_metrics(valid[true_col], valid[pred_col])

            if pd.notna(r2):
                legend_label = f"{label} (R² = {r2:.3f})"
            else:
                legend_label = f"{label} (R² = N/A)"

            ax.scatter(valid[true_col], valid[pred_col], label=legend_label, alpha=0.75)

    valid_true = df[true_col].dropna()

    if len(valid_true) > 0:
        min_val = min(valid_true.min(), df[list(methods_dict.values())].min().min())
        max_val = max(valid_true.max(), df[list(methods_dict.values())].max().max())
        ax.plot([min_val, max_val], [min_val, max_val], linestyle="--", label="1:1 line")

    ax.set_xlabel("Observed Frequency (Hz)")
    ax.set_ylabel("Predicted Frequency (Hz)")
    ax.set_title(title)
    ax.legend(fontsize=8)
    ax.grid(True, alpha=0.3)

    path = os.path.join(output_dir, filename)
    fig.tight_layout()
    fig.savefig(path, dpi=300, bbox_inches="tight")
    plt.close(fig)

    figure_paths.append(path)
    return path

def plot_performance_bar(perf_df, target, metric, title, filename):
    data = perf_df[perf_df["Frequency"] == target].copy()
    data = data.sort_values(metric)

    fig, ax = plt.subplots(figsize=(9, 5))
