def build_lightgbm_model():
    lgbm_pipe = Pipeline([
        ("scaler", StandardScaler()),
        ("model", LGBMRegressor(
            objective="regression",
            random_state=42,
            verbose=-1
        ))
    ])

    lgbm_ttr = TransformedTargetRegressor(
        regressor=lgbm_pipe,
        func=np.log1p,
        inverse_func=np.expm1
    )

    lgbm_params = {
        "regressor__model__n_estimators": [200, 400, 600],
        "regressor__model__learning_rate": [0.03, 0.05, 0.1],
        "regressor__model__max_depth": [-1, 4, 6],
        "regressor__model__num_leaves": [15, 31, 63],
        "regressor__model__min_child_samples": [5, 10, 20]
    }

    return lgbm_ttr, lgbm_params


