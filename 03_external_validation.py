def clean_numeric_columns(df, cols):
    for col in cols:
        if col in df.columns:
            df[col] = (
                df[col]
                .astype(str)
                .str.replace(",", ".", regex=False)
                .str.replace(" ", "", regex=False)
                .str.strip()
            )
            df[col] = pd.to_numeric(df[col], errors="coerce")
    return df


def calculate_metrics(y_true, y_pred):
    y_true = pd.Series(y_true)
    y_pred = pd.Series(y_pred)

    valid = pd.notna(y_true) & pd.notna(y_pred)

    y_true = np.array(y_true[valid], dtype=float)
    y_pred = np.array(y_pred[valid], dtype=float)

    if len(y_true) == 0:
        return np.nan, np.nan, np.nan, np.nan

    mae = mean_absolute_error(y_true, y_pred)
    rmse = np.sqrt(mean_squared_error(y_true, y_pred))

    if len(y_true) > 1:
        r2 = r2_score(y_true, y_pred)
    else:
        r2 = np.nan

    nonzero = y_true != 0
    if np.any(nonzero):
        mape = np.mean(np.abs((y_true[nonzero] - y_pred[nonzero]) / y_true[nonzero])) * 100
    else:
        mape = np.nan

    return mae, rmse, r2, mape


def add_dataframe_table_to_doc(doc, df, title=None, decimals=4):
    if title is not None:
        doc.add_heading(title, level=2)

    table = doc.add_table(rows=1, cols=len(df.columns))
    table.style = "Table Grid"

    hdr = table.rows[0].cells
    for j, col in enumerate(df.columns):
        hdr[j].text = str(col)

    for _, row in df.iterrows():
        cells = table.add_row().cells
        for j, col in enumerate(df.columns):
            val = row[col]

            if isinstance(val, float) or isinstance(val, np.floating):
                if pd.isna(val):
                    cells[j].text = ""
                else:
                    cells[j].text = f"{val:.{decimals}f}"
            else:
                if pd.isna(val):
                    cells[j].text = ""
                else:
                    cells[j].text = str(val)

    doc.add_paragraph("")


